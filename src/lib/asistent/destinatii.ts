/*
 * Drumul de click se CALCULEAZĂ din arborele de meniu, nu se scrie.
 *
 * Dacă s-ar scrie de mână, s-ar desincroniza de sidebar la prima reorganizare a
 * meniului, iar asistentul ar dicta cu încredere un drum care nu mai există —
 * mai rău decât niciun drum, fiindcă omul îl caută și nu-l găsește. Aici,
 * mutarea unei intrări dintr-un grup în altul schimbă automat ce spune
 * asistentul.
 */
function calculeazaDrum(intrare: Intrare): readonly string[] {
  const drum: string[] = [];

  if (intrare.zona === "app") {
    const parinte = NAV_ITEMS.find((item) => item.id === intrare.parinte);
    if (parinte !== undefined) {
      const grup = NAV_GROUPS.find((g) => g.id === parinte.group);
      if (grup !== undefined) drum.push(grup.label);
      drum.push(parinte.label);
    }
  } else {
    const parinte = PORTAL_NAV_ITEMS.find((item) => item.id === intrare.parinte);
    if (parinte !== undefined) {
      const grup = PORTAL_NAV_GROUPS.find((g) => g.id === parinte.group);
      if (grup !== undefined) drum.push(grup.label);
      drum.push(parinte.label);
    }
  }

  // Fila e ultimul pas doar dacă spune altceva decât părintele: pe `/pontaj`,
  // părintele e „Pontaj" și fila „Prezența" — două pași reali. Pe `/anunturi`
  // nu există bandă de file, deci drumul se oprește la intrarea de meniu.
  if (intrare.fila !== null && intrare.fila !== drum.at(-1)) drum.push(intrare.fila);

  // O rută fără părinte de meniu (`/profil`, `/notificari`) rămâne cu propria
  // etichetă: e mai bine decât un drum gol, care s-ar randa ca o pastilă mută.
  if (drum.length === 0) drum.push(intrare.eticheta);

  return drum;
}

export const DESTINATII: readonly Destinatie[] = INTRARI.map((intrare) => ({
  ...intrare,
  drum: calculeazaDrum(intrare),
}));

const DUPA_ID: ReadonlyMap<string, Destinatie> = new Map(DESTINATII.map((d) => [d.id, d]));

/** `undefined` pentru un identificator inventat — apelantul îl aruncă tăcut. */
export function destinatiaDupaId(id: string): Destinatie | undefined {
  return DUPA_ID.get(id);
}
