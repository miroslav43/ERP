// src/lib/asistent/destinatii.ts
/**
 * Lista ÎNCHISĂ de locuri către care asistentul are voie să trimită.
 *
 * Ăsta e mecanismul care face imposibilă halucinația de link, și merită spus de
 * ce nu e o chestiune de prompt. Un model căruia i se cere „scrie adresa paginii"
 * va scrie `/pontaj/orele-mele` — sună exact ca o rută a acestei aplicații, nu e
 * o invenție absurdă, și e un 404. Nicio formulare fermă din promptul de sistem
 * nu elimină clasa asta de greșeli; ea dispare abia când modelul nu mai are
 * ocazia să scrie o adresă.
 *
 * Aici modelul primește doar `id`-uri și poate emite doar `[[ruta:<id>]]`.
 * Href-ul, eticheta, iconița și drumul de click le desenează aplicația, din
 * datele de mai jos. Un `id` care nu există se aruncă la randare
 * (`marcaje.ts`), deci cel mai rău lucru care se poate întâmpla e o referință
 * lipsă — niciodată una greșită.
 *
 * ── DE CE E SCRISĂ DE MÂNĂ, ȘI NU GENERATĂ ───────────────────────────────────
 * Rutele se pot enumera mecanic din `src/app/**​/page.tsx`, iar `permission` se
 * poate ghici din `can(...)`-ul din capul fiecărei pagini. Ce NU se poate genera
 * e `descriere`: „ce faci pe ecranul ăsta, spus unui om care nu știe unde e".
 * Aia e conținutul propriu-zis al asistentului, și e singurul motiv pentru care
 * el e mai util decât paleta Cmd+K, care are deja căutare pe etichete.
 *
 * Împotriva îmbătrânirii tăcute stă `destinatii.test.ts`: parcurge arborele de
 * rute de pe disc și cere ca fiecare rută statică să fie ori aici, ori în
 * `EXCLUSE` cu motiv scris. Exact tiparul lui `permissions.test.ts`, care
 * compară codul cu seed-ul SQL. Fără poarta aia, fișierul devine în trei luni
 * `docs/conturi-si-rute.md`: două rute documentate care nu există și
 * unsprezece existente nedocumentate.
 *
 * ── PERMISIUNILE DE AICI SUNT PORȚI DE INTRARE, NU DE ACȚIUNE ────────────────
 * `permission` + `minScope` sunt cele care decid dacă pagina se deschide sau
 * întoarce `AccesRestricționat` — citite din porțile reale ale paginilor, nu din
 * documentație. Butoanele dinăuntru cer adesea mai mult (`/pontaj` se deschide
 * cu `attendance:read` own, dar aprobarea cere `approve` team); asta nu ne
 * privește aici, fiindcă asistentul trimite spre ecran, nu apasă butoane.
 *
 * Unde nav-ul declară un prag mai strict decât pagina, se ia al nav-ului. La
 * îndoială se alege VARIANTA STRICTĂ: o destinație ascunsă degeaba e o pierdere
 * mică, una oferită și apoi refuzată e chiar defectul pe care fișierul ăsta
 * există ca să-l prevină.
 */
