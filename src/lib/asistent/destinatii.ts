/** Datele scrise de mână. `drum` lipsește: se calculează. */
type Intrare = Readonly<{
  id: string;
  href: string;
  eticheta: string;
  zona: ZonaAsistent;
  /** `id`-ul intrării de meniu sub care stă ruta. `null` doar pentru rădăcini. */
  parinte: string | null;
  /** Eticheta filei din banda paginii, când se ajunge printr-o filă. */
  fila: string | null;
  featureKey: FeatureKey | null;
  permission: PermissionKey | null;
  minScope: MinScope;
  descriere: string;
}>;

export type Destinatie = Intrare &
  Readonly<{
    /** Drumul de click, gata de citit: ["Operațiuni", "Pontaj", "Perioade"]. */
    drum: readonly string[];
  }>;

